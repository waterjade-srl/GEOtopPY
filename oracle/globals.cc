// Some linked functions write scratch/log files here unconditionally (e.g.
// clouds.cc's cloudiness()/find_cloudiness() append to WORKING_DIRECTORY +
// "clouds.txt" with no way to disable it) -- a null WORKING_DIRECTORY (main()
// is the only place that would normally set it) segfaults the first time one
// of those runs. Point it at a scratch directory the oracle creates on load,
// well away from both the reference checkout and this repo -- the file
// content is never read back, only its existence matters.
namespace
{
const char *init_working_directory()
{
    const char *dir = "/tmp/geotop_oracle_scratch/";
    mkdir(dir, 0755);  // ignore EEXIST and any other failure: best-effort
    return dir;
}
}  // namespace

const char *WORKING_DIRECTORY = init_working_directory();

time_t start_time;
double elapsed_time, elapsed_time_start, cum_time, max_time;

/* version.cc is generated by meson and only geotop.cc uses it. */
const char *version() { return "oracle"; }
const char *commit() { return "oracle"; }
