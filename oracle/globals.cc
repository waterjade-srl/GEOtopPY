/* Definitions for the globals that geotop.cc owns.
 *
 * The oracle links every GEOtop translation unit except geotop.cc (which holds
 * main()), so the globals that file defines have to be provided here.
 *
 * Most are only storage. The three "novalue" sentinels are NOT: GEOtop sets
 * them at the top of main() (geotop.cc:157-159) and code all over the model
 * compares against them, so leaving them zero would make every "is this
 * absent?" test wrong. gt_inpts_open in particular fills missing keywords with
 * number_novalue. They are initialised here to exactly what main() assigns.
 *
 * Mirrors geotop.cc:57-99 and :157-159.
 */

